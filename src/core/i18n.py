class I18nManager(QObject):
    """Quản lý ngôn ngữ và phát tín hiệu khi chuyển đổi ngôn ngữ."""

    language_changed = Signal(str)

    def __init__(self, default_lang: str = DEFAULT_LANGUAGE):
        super().__init__()
        self._current_lang = default_lang if default_lang in SUPPORTED_LANGUAGES else DEFAULT_LANGUAGE

    @property
    def current_language(self) -> str:
        return self._current_lang

    def set_language(self, lang: str, emit_signal: bool = True):
        if lang not in SUPPORTED_LANGUAGES:
            logger.warning("Ngôn ngữ không được hỗ trợ: %s (chỉ hỗ trợ %s)", lang, SUPPORTED_LANGUAGES)
            return
        if self._current_lang != lang:
            self._current_lang = lang
            logger.info("Chuyển đổi ngôn ngữ hiển thị sang: %s", lang)
            if emit_signal:
                self.language_changed.emit(lang)


# Instance toàn cục để chia sẻ giữa các module UI
i18n = I18nManager()


def tr(key: str, **kwargs) -> str:
    """Tra cứu bản dịch theo ngôn ngữ hiện tại, fallback về tiếng Việt."""
    lang = i18n.current_language
    text = TRANSLATIONS.get(lang, {}).get(key)
    if text is None:
        text = TRANSLATIONS.get("vi", {}).get(key, key)
    if kwargs:
        try:
            return text.format(**kwargs)
        except Exception:
            return text
    return text


def get_character_skins(lang: Optional[str] = None) -> dict[str, str]:
    """Danh mục nhân vật Chibi theo ngôn ngữ (có Character Pack → của pack) + nhân vật bundle ĐÃ mở khoá (key `pack/char`)."""
    from src.config import CHARACTER_PACK, CHARACTER_SKINS   # import muộn: config import i18n
    from src.core.skin_unlock_gate import is_bundled_skin_key, is_skin_unlocked
    if CHARACTER_PACK is not None:
        base = {k: v for k, v in CHARACTER_SKINS.items() if not is_bundled_skin_key(k)}
    else:
        base = dict(CHARACTER_SKINS_BY_LANG.get(lang or i18n.current_language, CHARACTER_SKINS_BY_LANG["vi"]))
    base.update({k: v for k, v in CHARACTER_SKINS.items() if is_bundled_skin_key(k) and is_skin_unlocked(k)})
    return base
